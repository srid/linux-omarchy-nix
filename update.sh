#!/usr/bin/env bash
# Sync sources.nix with the pinned `omarchy-pkgs` input.
#
# The patch set and kernel config come from that input at build time, so an
# update is: bump the input, read the PKGBUILD's pkgver, prefetch the matching
# kernel.org tarball, rewrite sources.nix.
set -euo pipefail
cd "$(dirname "$0")"

echo "==> bumping the omarchy-pkgs input"
nix flake update omarchy-pkgs

src=$(nix eval --raw --impure --expr 'let f = builtins.getFlake (toString ./.); in f.inputs.omarchy-pkgs.outPath')
pkgbuild="$src/pkgbuilds/linux-omarchy/PKGBUILD"
version=$(sed -n 's/^pkgver=//p' "$pkgbuild" | head -1)
major=${version%%.*}
rev=$(jq -r '.nodes."omarchy-pkgs".locked.rev' flake.lock)

url="https://cdn.kernel.org/pub/linux/kernel/v${major}.x/linux-${version}.tar.xz"
echo "==> omarchy-pkgs ${rev:0:12} pins linux-omarchy $version"
echo "==> prefetching $url"
hash=$(nix store prefetch-file --json --hash-type sha256 "$url" | jq -r .hash)

cat > sources.nix <<EOF
# Generated by \`just update\` — do not edit by hand.
#
# Pinned to the linux-omarchy PKGBUILD that the \`omarchy-pkgs\` flake input points
# at (see flake.lock). The patch set and kernel config are read from that input,
# so only the version and the kernel.org tarball hash live here.
{
  version = "$version";
  srcHash = "$hash";
}
EOF

echo "==> wrote sources.nix (version $version)"
